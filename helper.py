"""The secrets.command helper: one generated shell script, scope chosen per profile by flag.

Root profile:   <root>/secret_guard/emit-secrets.sh --root   (all + default-only secrets)
Other profiles: <root>/secret_guard/emit-secrets.sh          (scope "all" only)

So a messaging bot token (default-only) never resolves in a second profile, and the multiplex
gateway's duplicate-credential preflight never trips (ISSUE-168). The script holds service and
variable NAMES only; values are read from the keychain at run time. Plain sh, no Python start-up:
Hermes kills a helper after 3 s by default.
"""

from __future__ import annotations

import os
import re
import shutil
import time
from pathlib import Path
from typing import Optional

from . import registry

HEADER = "# Generated by Secret Guard from registry.json. Do not edit; run `hermes secret helper`.\n"


def root_home() -> Path:
    from hermes_constants import get_default_hermes_root
    return Path(get_default_hermes_root())


def helper_path() -> Path:
    return root_home() / "secret_guard" / "emit-secrets.sh"


def _q(s: str) -> str:
    if not re.match(r"^[A-Za-z0-9._@/ -]+$", s):
        raise ValueError(f"unsafe name in registry: {s!r}")
    return "'" + s + "'"


def render() -> str:
    secrets = registry.load()["secrets"]
    lines = ["#!/bin/sh", HEADER.rstrip("\n"),
             "ROOT=0; [ \"$1\" = \"--root\" ] && ROOT=1",
             "emit() {  # service account keychain ENV",
             "  v=$(/usr/bin/security find-generic-password -w -s \"$1\" -a \"$2\" $3 2>/dev/null) || return 0",
             "  [ -n \"$v\" ] && printf '%s=%s\\n' \"$4\" \"$v\"",
             "}"]
    def line(e):
        kc = _q(e["keychain"]) if e.get("keychain") else "''"
        return f"emit {_q(e['service'])} {_q(e['account'])} {kc} {e['env']}"
    for env in sorted(secrets):
        e = secrets[env]
        if e["scope"] == "all":
            lines.append(line(e))
    root_only = [secrets[k] for k in sorted(secrets) if secrets[k]["scope"] == "default-only"]
    if root_only:
        lines.append("if [ \"$ROOT\" = 1 ]; then")
        lines += ["  " + line(e) for e in root_only]
        lines.append("fi")
    lines.append("exit 0")
    # an empty keychain arg must not reach security as ''; drop it
    return "\n".join(lines).replace(" '' ", " \"\" ") + "\n"


def write() -> Path:
    p = helper_path()
    p.parent.mkdir(parents=True, exist_ok=True)
    os.chmod(p.parent, 0o700)
    tmp = p.with_suffix(".sh.tmp")
    tmp.write_text(render())
    os.chmod(tmp, 0o700)
    os.replace(tmp, p)
    return p


def is_current() -> bool:
    p = helper_path()
    return p.exists() and p.read_text() == render()

# ---------------------------------------------------------------- wiring profiles

def profile_home(name: Optional[str]) -> Path:
    root = root_home()
    if not name or name == "default":
        return root
    if not re.match(r"^[A-Za-z0-9._-]+$", name):
        raise ValueError("bad profile name")
    return root / "profiles" / name


def command_for(name: Optional[str]) -> str:
    cmd = str(helper_path())
    return cmd + " --root" if (not name or name == "default") else cmd


def wire(name: Optional[str]) -> str:
    """Point one profile's secrets.command at the Secret Guard helper.

    Never uses `hermes config set` (it rewrites the whole file and strips comments). Appends a block
    when there is no `secrets:` key; replaces the existing command string when it occurs exactly
    once; otherwise refuses and says what to do. Backs up first; checks the YAML parses after.
    """
    import yaml
    home = profile_home(name)
    cfg = home / "config.yaml"
    if not cfg.exists():
        raise FileNotFoundError(f"no config.yaml at {home}")
    text = cfg.read_text()
    data = yaml.safe_load(text) or {}
    want = command_for(name)
    cur = (((data.get("secrets") or {}).get("command") or {}).get("command"))
    if cur == want and ((data.get("secrets") or {}).get("command") or {}).get("enabled"):
        return f"{name or 'default'}: already wired"
    backup = cfg.with_name(f"config.yaml.bak-secret-guard-{time.strftime('%Y%m%d-%H%M%S')}")
    shutil.copy2(cfg, backup)
    if "secrets" not in data:
        block = ("\n# Secret Guard: keys come from the keychain via one generated helper.\n"
                 "secrets:\n  command:\n    enabled: true\n"
                 f"    command: \"{want}\"\n    override_existing: true\n")
        new = text + ("" if text.endswith("\n") else "\n") + block
    elif isinstance(cur, str) and cur and text.count(cur) == 1:
        new = text.replace(cur, want)
    else:
        raise RuntimeError(f"{cfg} has a secrets: block this tool won't edit safely. Set "
                           f"secrets.command.command to \"{want}\" by hand (backup: {backup.name}).")
    parsed = yaml.safe_load(new) or {}
    if (parsed.get("secrets") or {}).get("command", {}).get("command") != want:
        raise RuntimeError("edit did not produce the expected config; file left unchanged")
    cfg.write_text(new)
    return f"{name or 'default'}: wired ({'appended block' if 'secrets' not in data else 'replaced helper path'}; backup {backup.name})"


def profiles() -> list[str]:
    root = root_home()
    names = ["default"]
    pdir = root / "profiles"
    if pdir.is_dir():
        names += sorted(p.name for p in pdir.iterdir() if (p / "config.yaml").exists())
    return names


def wiring_report() -> list[tuple[str, str]]:
    """(profile, state) where state is ok / not wired / other helper / WRONG SCOPE."""
    import yaml
    out = []
    hp = str(helper_path())
    for n in profiles():
        try:
            data = yaml.safe_load((profile_home(n) / "config.yaml").read_text()) or {}
        except Exception:
            out.append((n, "config unreadable"))
            continue
        cmd = (((data.get("secrets") or {}).get("command") or {}).get("command")) or ""
        if not cmd:
            out.append((n, "not wired"))
        elif hp not in cmd:
            out.append((n, "other helper"))
        elif (n == "default") != cmd.rstrip().endswith("--root"):
            out.append((n, "WRONG SCOPE (multiplex blocker)" if n != "default" else "WRONG SCOPE (root lacks --root; bot tokens missing)"))
        else:
            out.append((n, "ok"))
    return out

# ---------------------------------------------------------------- importing an existing helper

_EMIT_RE = re.compile(r'^\s*emit\s+"([A-Za-z0-9._-]+)"\s+"([A-Z][A-Z0-9_]+)"', re.M)


def parse_existing_helper(path: Path) -> list[tuple[str, str]]:
    """(service, ENV) pairs from a keychain-secrets-env.sh-style script. Reads names only; never runs it."""
    return _EMIT_RE.findall(path.read_text())
